"""SENTINEL regression test for finding fnd_7e872f8065751052 (CWE-89).

Property under test: user-controlled input must never be interpolated into the SQL text
passed to the database driver; it must be bound as a parameter instead.

Generated by playbook `sqli-dbapi-v1`. The target is exercised against a recording stand-in for
the DB-API connection, so no database or network is required.
"""

import importlib.util
import inspect
import pathlib
import sqlite3
import sys

import pytest

ROOT = pathlib.Path(__file__).resolve().parents[1]
TARGET_FILE = ROOT / "app.py"
TARGET_FUNCTION = "login"
CONN_NAMES = ('conn', 'connection', 'db', 'database', 'cursor', 'cur', 'session')
PAYLOADS = ["x' OR '1'='1", "'; DROP TABLE users; --"]


class _Recorder:
    def __init__(self):
        self.calls = []
        self.row_factory = None
        self.rowcount = 0
        self.lastrowid = 0

    def execute(self, sql, params=None, *args, **kwargs):
        self.calls.append((sql, params))
        return self

    executemany = execute
    executescript = execute

    def cursor(self, *args, **kwargs):
        return self

    def fetchone(self):
        return None

    def fetchall(self):
        return []

    def fetchmany(self, *args, **kwargs):
        return []

    def __iter__(self):
        return iter(())

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        return False

    def __getattr__(self, name):
        return lambda *a, **k: self


class _Anything(dict):
    """Stand-in for request.form / args / values: every key holds the payload."""

    def __init__(self, payload):
        super().__init__()
        self._payload = payload

    def get(self, key, default=None, type=None):
        return self._payload

    def __getitem__(self, key):
        return self._payload

    def __contains__(self, key):
        return True

    def getlist(self, key):
        return [self._payload]


def _load_module():
    sys.path.insert(0, str(ROOT))
    spec = importlib.util.spec_from_file_location("sentinel_target_module", TARGET_FILE)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _flask_app(module):
    for value in vars(module).values():
        cls = type(value)
        if cls.__name__ == "Flask" and cls.__module__.split(".")[0] == "flask":
            return value
    return None


def _call(module, target, kwargs, payload):
    """Call the target; a Flask view runs inside a request whose every input field carries the payload."""
    flask_app = _flask_app(module)
    if flask_app is None:
        return target(**kwargs)
    import flask

    with flask_app.test_request_context("/", method="POST"):
        req = flask.request._get_current_object()
        req.form = req.args = req.values = req.cookies = _Anything(payload)
        req.get_json = lambda *a, **k: _Anything(payload)
        return target(**kwargs)


@pytest.mark.parametrize("payload", PAYLOADS)
def test_fnd_7e872f8065751052_user_input_is_bound_not_interpolated(payload, monkeypatch):
    recorder = _Recorder()
    monkeypatch.setattr(sqlite3, "connect", lambda *a, **k: recorder)
    module = _load_module()
    target = getattr(module, TARGET_FUNCTION)
    kwargs = {}
    for name, param in inspect.signature(target).parameters.items():
        if param.kind in (param.VAR_POSITIONAL, param.VAR_KEYWORD):
            continue
        kwargs[name] = recorder if name in CONN_NAMES else payload
    try:
        _call(module, target, kwargs, payload)
    except Exception:
        pass  # the target may choke on the recorder's empty results after it has issued its query
    if not recorder.calls:
        pytest.skip("target issued no SQL statement; cannot assess")
    leaked = [sql for sql, _ in recorder.calls if payload in sql]
    assert not leaked, f"user input was interpolated into SQL text: {leaked[0]!r}"
